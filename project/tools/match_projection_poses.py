"""Pick a stand-in pose for each of Shadow's shadow sprites, until they are authored in the pose editor.

Shadow's shadows (the projectile animations of his slide, P41 and grab, and their hit and return frames) are
drawn from sprites that no authored move uses, so the viewer has no pose for them. Each one is a Shadow
body, so this finds the authored Shadow sprite whose silhouette overlaps it best (intersection over union,
searched over every shift of up to 100 source pixels) and records the pose to borrow and how far its origin
lies from the projectile's. The viewer uses that pose only while the shadow sprite has none of its own.

    python project/tools/match_projection_poses.py

Writes project/prototype/projection_poses.h. Run it after authoring poses, since new poses become candidates.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import fit_poses as fp  # noqa: E402
import paths  # noqa: E402

HAR = 1
SPRITES = paths.ARTIFACTS / "pose-reference" / "shadow"
# projectile animation -> number of sprites
TARGETS = {22: 2, 53: 2, 25: 3, 26: 3, 37: 1, 52: 1, 39: 1, 40: 3, 50: 3, 51: 3, 38: 2, 28: 2, 27: 2, 29: 2, 49: 1}
# animations that draw exactly the sprites of another animation of Shadow's own: (borrowed animation, sprite count)
EXACT = {34: (44, 5), 35: (44, 5)}
SEARCH = 100


def mask(anim, sprite):
    path = SPRITES / str(anim) / f"sprite-{sprite:02d}.png"
    return np.array(Image.open(path).convert("RGBA"))[:, :, 3] > 0 if path.exists() else None


def best_shift(target, cand):
    """Shift (dx, dy) of the candidate against the target and the IoU there; both masks are placed at their own
    offsets, so shifts are relative to each sprite's own origin."""
    (tm, (tx, ty)), (cm, (cx, cy)) = target, cand
    size = (tm.shape[0] + cm.shape[0] + 2 * SEARCH, tm.shape[1] + cm.shape[1] + 2 * SEARCH)
    ft = np.fft.rfft2(tm.astype(float), size)
    fc = np.fft.rfft2(cm[::-1, ::-1].astype(float), size)
    inter = np.fft.irfft2(ft * fc, size)          # inter[i, j]: overlap with the candidate's origin shifted by i, j
    union = tm.sum() + cm.sum() - inter
    iou = inter / np.maximum(union, 1)
    ry0 = cy - ty + cm.shape[0] - 1                # array row of shift dy = 0
    rx0 = cx - tx + cm.shape[1] - 1
    lo_y, hi_y = max(ry0 - SEARCH, 0), min(ry0 + SEARCH, size[0] - 1)
    lo_x, hi_x = max(rx0 - SEARCH, 0), min(rx0 + SEARCH, size[1] - 1)
    window = iou[lo_y:hi_y + 1, lo_x:hi_x + 1]
    i, j = np.unravel_index(np.argmax(window), window.shape)
    at, best = (lo_x + j - rx0, lo_y + i - ry0), float(window[i, j])
    return at, best


def main():
    authored = []
    with (paths.DATA / "pose_catalog.csv").open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if int(r["har"]) == HAR and "arm" in r["flags"] and "leg" in r["flags"]:
                authored.append((int(r["animation"]), int(r["sprite"])))
    cands = []
    for a, s in sorted(set(authored)):
        m = mask(a, s)
        if m is not None and m.any():
            cands.append(((a, s), (m, fp.sprite_offset(HAR, a, s))))
    lines = ["// Generated by match_projection_poses.py. Do not edit directly.",
             "// Stand-in poses for Shadow's shadow sprites: borrow (from_anim, from_sprite)'s pose with its origin",
             "// (dx, dy) source pixels from the projectile's origin (y down).",
             "typedef struct { int anim, sprite, from_anim, from_sprite, dx, dy; } ProjectionPose;",
             "static const ProjectionPose projection_poses[] = {"]
    for anim, count in sorted(TARGETS.items()):
        for sprite in range(count):
            tm = mask(anim, sprite)
            if tm is None or not tm.any():
                continue
            target = (tm, fp.sprite_offset(HAR, anim, sprite))
            scored = []
            for key, cand in cands:
                (dx, dy), iou = best_shift(target, cand)
                scored.append((iou, key, dx, dy))
            iou, (fa, fs), dx, dy = max(scored)
            print(f"{anim}/{sprite} <- {fa}/{fs}  iou {iou:.2f}  shift ({dx}, {dy})")
            lines.append(f"    {{{anim}, {sprite}, {fa}, {fs}, {dx}, {dy}}},")
    for anim, (src, count) in sorted(EXACT.items()):
        for sprite in range(count):
            (ox, oy), (sx, sy) = fp.sprite_offset(HAR, anim, sprite), fp.sprite_offset(HAR, src, sprite)
            print(f"{anim}/{sprite} <- {src}/{sprite}  exact  shift ({ox - sx}, {oy - sy})")
            lines.append(f"    {{{anim}, {sprite}, {src}, {sprite}, {ox - sx}, {oy - sy}}},")
    lines += ["};", ""]
    out = paths.PROTOTYPE / "projection_poses.h"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"-> {out}")


if __name__ == "__main__":
    main()
